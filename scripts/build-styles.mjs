import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";

const FILES = [
  "src/styles/tokens.css",
  "src/styles/base.css",
  "src/styles/views/home.css",
  "src/styles/views/library.css",
  "src/styles/views/projects.css",
  "src/styles/views/prompt.css",
  "src/styles/modals.css",
  "src/styles/views/books.css",
  "src/styles/views/migration.css",
  "src/styles/responsive.css",
  "src/styles/cards/01-library-tools.css",
  "src/styles/cards/02-home.css",
  "src/styles/cards/03-projects.css",
  "src/styles/cards/04-prompt.css",
  "src/styles/cards/05-library-list.css",
  "src/styles/cards/06-frame.css",
  "src/styles/cards/07-books.css",
  "src/styles/cards/08-components.css",
  "src/styles/cards/09-webclip-cover.css",
  "src/styles/cards/10-home-shortcuts.css",
  "src/styles/cards/11-books-tools.css",
  "src/styles/cards/12-components.css",
  "src/styles/cards/13-home-weeks.css",
  "src/styles/cards/14-modals.css",
  "src/styles/views/tsubuyaki.css",
  "src/styles/tabs.css",
  "src/styles/ui/system.css",
];

const HEADER =
  "/* Generated by scripts/build-styles.mjs. Do not edit this file directly. */\n\n";

const css =
  HEADER +
  (await Promise.all(FILES.map((file) => readFile(file, "utf8")))).join("");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile("styles.css", "utf8");
  } catch {
    // 未生成なら不一致として扱う。
  }
  if (current !== css) {
    console.error("styles.css is out of date. Run pnpm styles:build.");
    process.exit(1);
  }
  console.log("styles.css is up to date.");
} else {
  await writeFile("styles.css", css);
  console.log(
    `Built styles.css from ${FILES.length} files (${css.length} bytes).`
  );
}
